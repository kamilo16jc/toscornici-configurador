const mancanti = new Set();

/**
 * Traduce un'etichetta o un valore.
 *
 * In italiano restituisce il testo com'e': nessun costo, nessun rischio.
 * In inglese cerca prima la corrispondenza esatta, poi i frammenti. Se non
 * trova nulla lascia l'italiano — meglio una parola italiana in mezzo che
 * un buco nel preventivo — e lo segnala in console.
 */
export function tr(testo, lingua) {
  if (lingua !== 'en' || testo == null) return testo;
  const s = String(testo);
  if (!s.trim()) return s;
  if (EN[s] !== undefined) return EN[s];

  let fuori = s;
  let toccato = false;
  for (const [re, con] of DENTRO) {
    if (re.test(fuori)) { fuori = fuori.replace(re, con); toccato = true; }
  }
  if (toccato) return fuori;

  /* Numeri, misure e nomi propri non hanno bisogno di traduzione:
     "900 × 2100 mm", "ARIANNA", "Tintoretto (90/70)". Si segnala solo
     quello che contiene parole italiane vere. */
  /* Misure e nomi propri non hanno bisogno di traduzione: "900 × 2100 mm",
     "22×70", "ARIANNA", "Tintoretto (90/70)". Le unita' vanno ammesse o
     ogni misura finisce nell'elenco di quel che manca — e un elenco pieno
     di falsi allarmi non lo guarda piu' nessuno. */
  if (/^[\d\s×x·,.\-—/()]*(mm|cm|m)?[\d\s×x·,.\-—/()]*$/i.test(s)) return s;
  if (/^[A-Z0-9\s·\-—/()"'.]+$/.test(s)) return s;
  if (!mancanti.has(s)) {
    mancanti.add(s);
    console.info('[preventivo/en] senza traduzione:', JSON.stringify(s));
  }
  return s;
}

